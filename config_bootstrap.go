package main

import (
	"crypto/rand"
	_ "embed"
	"encoding/hex"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

//go:embed config.example.toml
var defaultConfigTemplate string

var (
	rePepper = regexp.MustCompile(`(?m)^pepper\s*=\s*".*"`)
	reKeyHex = regexp.MustCompile(`(?m)^key_hex\s*=\s*".*"`)
)

// ensureConfigFile creates configPath from the embedded template when it is
// missing, then fills in freshly generated secrets. It reports whether the
// file was created so the caller can tell the user exactly once.
func ensureConfigFile(configPath string) (created bool, err error) {
	if configPath == "" {
		return false, nil
	}
	_, statErr := os.Stat(configPath)
	if statErr == nil {
		return false, nil
	}
	if !os.IsNotExist(statErr) {
		return false, fmt.Errorf("检查配置文件 %s: %w", configPath, statErr)
	}
	if dir := filepath.Dir(configPath); dir != "" && dir != "." {
		if err := os.MkdirAll(dir, 0o750); err != nil {
			return false, fmt.Errorf("创建配置目录 %s: %w", dir, err)
		}
	}
	pepper, err := randomHex(32)
	if err != nil {
		return false, err
	}
	key, err := randomHex(32)
	if err != nil {
		return false, err
	}
	content := rePepper.ReplaceAllString(defaultConfigTemplate, `pepper = "`+pepper+`"`)
	content = reKeyHex.ReplaceAllString(content, `key_hex = "`+key+`"`)
	content = strings.ReplaceAll(content, "# 复制为 config.toml 后按需修改：cp config.example.toml config.toml\n#",
		"# 本文件由 gitli 首次启动自动生成，可直接编辑。\n#")
	if err := os.WriteFile(configPath, []byte(content), 0o600); err != nil {
		return false, fmt.Errorf("写入配置文件 %s: %w", configPath, err)
	}
	return true, nil
}

// ensureSecret fills a missing secret in an existing config file so an upgrade
// from an older generated file still ends up with working encryption.
func ensureSecret(configPath, kind string) (string, error) {
	re := rePepper
	if kind == "key_hex" {
		re = reKeyHex
	}
	value, err := randomHex(32)
	if err != nil {
		return "", err
	}
	raw, err := os.ReadFile(configPath)
	if err != nil {
		return "", err
	}
	updated := re.ReplaceAllString(string(raw), kind+` = "`+value+`"`)
	if updated == string(raw) {
		return "", fmt.Errorf("配置文件中找不到 %s 字段", kind)
	}
	info, err := os.Stat(configPath)
	mode := os.FileMode(0o600)
	if err == nil {
		mode = info.Mode().Perm()
	}
	if err := os.WriteFile(configPath, []byte(updated), mode); err != nil {
		return "", err
	}
	return value, nil
}

// ensureConfiguredSecrets backfills encryption secrets in an existing config
// file. Environment variables still win, so this only handles the common case
// of a file generated by an older version.
func ensureConfiguredSecrets(configPath string) error {
	if configPath == "" {
		return nil
	}
	if os.Getenv("GITLI_PEPPER") == "" || os.Getenv("GITLI_CRYPTO_KEY") == "" {
		raw, err := os.ReadFile(configPath)
		if err != nil {
			return nil
		}
		if os.Getenv("GITLI_PEPPER") == "" && regexp.MustCompile(`(?m)^pepper\s*=\s*""\s*$`).Match(raw) {
			if _, err := ensureSecret(configPath, "pepper"); err != nil {
				return err
			}
			fmt.Println("config.toml 缺少 pepper，已自动生成并写回。")
		}
		if os.Getenv("GITLI_CRYPTO_KEY") == "" && regexp.MustCompile(`(?m)^key_hex\s*=\s*""\s*$`).Match(raw) {
			if _, err := ensureSecret(configPath, "key_hex"); err != nil {
				return err
			}
			fmt.Println("config.toml 缺少加密密钥，已自动生成并写回。")
		}
	}
	return nil
}

func randomHex(n int) (string, error) {
	buf := make([]byte, n)
	if _, err := rand.Read(buf); err != nil {
		return "", fmt.Errorf("生成随机密钥: %w", err)
	}
	return hex.EncodeToString(buf), nil
}
